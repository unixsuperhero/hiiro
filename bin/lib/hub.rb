require 'json'
require 'fileutils'

# A central filesystem hub: ~/hub holds only symlinks to existing locations plus
# a catalog (.hub.json) describing them. Originals are never moved, deleted or
# changed, and file contents are never read (only the hub's own catalog and
# generated READMEs).
class Hub
  class Error < StandardError; end
  class Usage < Error; end

  CATALOG_FILE    = '.hub.json'.freeze
  README_FILE     = 'README.md'.freeze
  RESERVED        = [CATALOG_FILE, README_FILE].map(&:downcase).freeze
  MARKER          = '<!-- h-hub: generated by `h hub sync`; delete this line to take ownership -->'.freeze
  BUNDLED_CATALOG = File.expand_path('hub-catalog.json', __dir__).freeze
  DEFAULT_LIMIT   = 100
  MAX_LIMIT       = 10_000
  FIND_EXCLUDES   = %w[.git node_modules .cache].freeze
  PROBLEM_STATES  = %i[missing_target conflict].freeze

  # state: :ok | :create | :update | :missing_target | :conflict | :skipped
  Item = Struct.new(:kind, :name, :path, :state, :detail) do
    def problem? = PROBLEM_STATES.include?(state)
    def pending? = %i[create update].include?(state)
  end

  attr_reader :root

  def initialize(root:, out: $stdout, err: $stderr)
    @root = File.expand_path(root)
    @out = out
    @err = err
  end

  # --- commands -------------------------------------------------------------

  def init(catalog_path = nil)
    source = catalog_path ? File.expand_path(catalog_path) : BUNDLED_CATALOG
    initialized = catalog_present?
    unless initialized
      text = read_source_catalog(source)
      validate_catalog(parse_catalog(text, source))
    end

    case root_state
    when :absent
      FileUtils.mkdir_p(File.dirname(root))
      Dir.mkdir(root, 0o700)
    when :dir
      if initialized
        @out.puts "hub already initialized at #{root}; syncing (catalog untouched)"
        @out.puts "ignoring #{catalog_path}" if catalog_path
        return sync
      end
      unless Dir.children(root).empty?
        raise Error, "#{root} is not empty and has no #{CATALOG_FILE}; refusing to initialize"
      end
    end

    write_atomic(catalog_file, text, 0o600)
    File.chmod(0o700, root)
    @out.puts "initialized #{root} from #{source}"
    sync
  end

  def sync(dry_run: false)
    catalog = load_catalog
    items = plan(catalog)
    apply(items, catalog) unless dry_run
    report(items, dry_run: dry_run)
    items.any?(&:problem?) ? 1 : 0
  end

  def doctor
    catalog = load_catalog
    items = plan(catalog)
    bad = items.select { |i| i.problem? || (i.pending? && i.kind != :readme) }
    bad.each { |i| @out.puts "#{i.state.to_s.tr('_', ' ')}: #{describe(i)}" }
    notes = items.select { |i| i.pending? && i.kind == :readme }
    notes.each { |i| @out.puts "note: #{describe(i)} (run sync)" }
    @out.puts bad.empty? ? "healthy: #{items.count(&:itself)} checks" : "unhealthy: #{bad.size} problem(s)"
    bad.empty? ? 0 : 1
  end

  def list(query = nil)
    catalog = load_catalog
    rows = catalog['directories'].map { |n, d| ['group', n, '', d] } +
           catalog['links'].map { |l| ['link', l['name'], l['target'], l['description']] }
    rows = rows.select { |r| r.join("\n").downcase.include?(query.downcase) } if query && !query.empty?
    rows.sort_by! { |r| r[1] }
    width = rows.map { |r| r[1].size }.max.to_i
    rows.each do |kind, name, target, desc|
      @out.puts [kind.ljust(5), name.ljust(width), (target.empty? ? '' : "-> #{target}  "), desc].join('  ').rstrip
    end
    rows.empty? ? 1 : 0
  end

  def path(name = nil)
    @out.puts(name.nil? ? root : File.join(root, resolve_name(load_catalog, name)))
    0
  end

  def open(name = nil)
    target = name.nil? ? root : File.join(root, resolve_name(load_catalog, name))
    raise Error, "#{target} does not exist (run: h hub sync)" unless File.exist?(target) || File.symlink?(target)

    system('open', target) ? 0 : 1
  end

  def find(name, query, limit: DEFAULT_LIMIT)
    raise Usage, 'find needs a non-empty QUERY' if query.to_s.empty?

    catalog = load_catalog
    name = resolve_name(catalog, name)
    base = File.join(root, name)
    raise Error, "#{name} is not synced (run: h hub sync)" unless File.exist?(base)
    raise Error, "#{name}: path crosses a symlink or non-directory" if parent_state(base) == :blocked

    @find = { needle: query.downcase, limit: limit, count: 0,
              followed: catalog['links'].map { |l| l['name'] }, stopped: false }
    if File.directory?(base)
      walk(base, name)
    elsif File.basename(base).downcase.include?(@find[:needle])
      emit_match(base)
    end
    @err.puts "stopped at --limit #{limit}" if @find[:stopped]
    @find[:count].zero? ? 1 : 0
  end

  def add(name, target, description)
    catalog = load_catalog
    description = description.to_s
    raise Usage, 'add needs a non-empty DESCRIPTION' if description.strip.empty?

    expanded = File.expand_path(target)
    raise Error, "target #{target} does not exist" unless File.exist?(expanded)

    stored = target.start_with?('~') ? target : expanded
    updated = Marshal.load(Marshal.dump(catalog))
    updated['links'] << { 'name' => name, 'target' => stored, 'description' => description }
    validate_catalog(updated)
    conflict = plan(updated).find { |i| i.kind == :link && i.name == name && i.problem? && i.state == :conflict }
    raise Error, "cannot add #{name}: #{conflict.detail} (catalog unchanged)" if conflict

    write_atomic(catalog_file, JSON.pretty_generate(updated) + "\n", 0o600)
    @out.puts "registered #{name} -> #{stored}"
    sync
  end

  # --- catalog --------------------------------------------------------------

  def catalog_file = File.join(root, CATALOG_FILE)

  def load_catalog
    unless catalog_present?
      raise Error, "hub not initialized at #{root} (run: h hub init)"
    end
    raise Error, "#{root} must be a real directory, not a symlink" unless root_state == :dir

    validate_catalog(parse_catalog(File.read(catalog_file), catalog_file))
  end

  def catalog_present?
    File.lstat(catalog_file).file?
  rescue SystemCallError
    false
  end

  def read_source_catalog(source)
    raise Error, "catalog #{source} is not a regular file" unless File.file?(source)

    File.read(source)
  rescue SystemCallError => e
    raise Error, "cannot read catalog #{source}: #{e.message}"
  end

  def parse_catalog(text, source)
    JSON.parse(text)
  rescue JSON::ParserError => e
    raise Error, "#{source}: invalid JSON (#{e.message.lines.first.to_s.strip})"
  end

  # Whole-catalog validation; returns the catalog. No filesystem writes.
  def validate_catalog(c)
    fail_catalog('catalog must be an object') unless c.is_a?(Hash)
    unknown = c.keys - %w[version description directories links]
    fail_catalog("unknown keys: #{unknown.join(', ')}") unless unknown.empty?
    fail_catalog('version must be 1') unless c['version'] == 1
    fail_catalog('description must be a string') unless c['description'].is_a?(String)
    dirs = c['directories']
    links = c['links']
    fail_catalog('directories must be an object of name => description') unless dirs.is_a?(Hash)
    fail_catalog('links must be an array') unless links.is_a?(Array)

    dirs.each do |name, desc|
      check_name(name)
      fail_catalog("directory #{name}: description must be a non-empty string") unless desc.is_a?(String) && !desc.strip.empty?
    end
    links.each_with_index do |l, i|
      fail_catalog("links[#{i}] must be an object") unless l.is_a?(Hash)
      extra = l.keys - %w[name target description]
      fail_catalog("links[#{i}]: unknown keys #{extra.join(', ')}") unless extra.empty?
      %w[name target description].each do |k|
        fail_catalog("links[#{i}].#{k} must be a non-empty string") unless l[k].is_a?(String) && !l[k].strip.empty?
      end
      check_name(l['name'])
      check_target(l['name'], l['target'])
    end

    names = dirs.keys + links.map { |l| l['name'] }
    folded = names.map(&:downcase)
    dup = folded.find { |n| folded.count(n) > 1 }
    fail_catalog("duplicate or conflicting name: #{names.find { |n| n.downcase == dup }}") if dup

    link_names = links.map { |l| l['name'] }
    names.each do |n|
      prefixes(n).each do |p|
        fail_catalog("#{n}: #{p} is a link and cannot contain other entries") if link_names.include?(p)
        fail_catalog("#{n}: parent directory #{p} is not declared in directories") unless dirs.key?(p)
      end
    end
    c
  end

  def check_name(name)
    fail_catalog("name must be a string: #{name.inspect}") unless name.is_a?(String)
    parts = name.split('/', -1)
    bad = name.empty? || name.start_with?('/') || name.match?(/[[:cntrl:]]/) ||
          parts.any? { |p| p.empty? || p == '.' || p == '..' || RESERVED.include?(p.downcase) }
    fail_catalog("invalid logical name #{name.inspect} (relative, no empty/./.. parts, not #{[CATALOG_FILE, README_FILE].join('/')}, any case)") if bad
  end

  def check_target(name, target)
    unless target.start_with?('/', '~')
      fail_catalog("#{name}: target must be absolute or start with ~ (#{target})")
    end
    expanded = File.expand_path(target)
    hub_lexical = root
    hub_real = resolve_loose(root)
    target_real = resolve_loose(expanded)
    if inside?(expanded, hub_lexical) || inside?(target_real, hub_real) || inside?(target_real, hub_lexical)
      fail_catalog("#{name}: target #{target} is inside the hub")
    end
  end

  def fail_catalog(msg) = raise(Error, "invalid catalog: #{msg}")

  def prefixes(name)
    parts = name.split('/')
    (1...parts.size).map { |i| parts[0, i].join('/') }
  end

  def resolve_name(catalog, name)
    n = name.to_s.chomp('/')
    known = catalog['directories'].keys + catalog['links'].map { |l| l['name'] }
    raise Error, "unknown hub entry #{name.inspect} (see: h hub list)" unless known.include?(n)

    n
  end

  # --- paths and guards -----------------------------------------------------

  def inside?(path, dir) = path == dir || path.start_with?(dir.end_with?('/') ? dir : dir + '/')

  # realpath of the longest existing prefix plus the not-yet-existing rest
  def resolve_loose(path)
    p = File.expand_path(path)
    rest = []
    loop do
      begin
        return File.join(File.realpath(p), *rest)
      rescue SystemCallError
        parent = File.dirname(p)
        return File.join(p, *rest) if parent == p

        rest.unshift(File.basename(p))
        p = parent
      end
    end
  end

  def root_state
    st = File.lstat(root)
    return :dir if st.directory?

    raise Error, "#{root} is a symlink; refusing to use it as hub root" if st.symlink?

    raise Error, "#{root} exists and is not a directory"
  rescue Errno::ENOENT
    :absent
  end

  # :ok, :absent (an ancestor is missing) or :blocked (symlink / non-directory ancestor)
  def parent_state(path)
    rel = File.dirname(path).delete_prefix(root).delete_prefix('/')
    cur = root
    rel.split('/').each do |part|
      cur = File.join(cur, part)
      st = File.lstat(cur)
      return :blocked unless st.directory? # lstat: symlinks are not directories
    rescue Errno::ENOENT
      return :absent
    end
    :ok
  end

  # --- plan / apply ---------------------------------------------------------

  def plan(catalog)
    dirs = catalog['directories']
    items = [root_item]
    dir_items = dirs.keys.sort_by { |n| [n.count('/'), n] }.map { |n| dir_item(n) }
    link_items = catalog['links'].sort_by { |l| l['name'] }.map { |l| link_item(l) }
    items.concat(dir_items, link_items)
    items << readme_item('/', catalog['description'], catalog, File.join(root, README_FILE), '(root)')
    dirs.keys.sort.each do |n|
      di = dir_items.find { |i| i.name == n }
      next if di.problem?

      items << readme_item(n, dirs[n], catalog, File.join(root, n, README_FILE), n)
    end
    items
  end

  def root_item
    mode = File.lstat(root).mode & 0o777
    return Item.new(:root, '(root)', root, :ok, '0700') if mode == 0o700

    Item.new(:root, '(root)', root, :update, format('chmod 0700 (was %04o)', mode))
  end

  def dir_item(name)
    path = File.join(root, name)
    return Item.new(:dir, name, path, :conflict, 'parent is a symlink or not a directory') if parent_state(path) == :blocked

    st = File.lstat(path)
    if st.symlink?
      Item.new(:dir, name, path, :conflict, 'is a symlink, not a real directory')
    elsif st.directory?
      Item.new(:dir, name, path, :ok, nil)
    else
      Item.new(:dir, name, path, :conflict, 'exists and is not a directory')
    end
  rescue Errno::ENOENT
    Item.new(:dir, name, path, :create, nil)
  end

  def link_item(link)
    name = link['name']
    path = File.join(root, name)
    target = File.expand_path(link['target'])
    return Item.new(:link, name, path, :conflict, 'parent is a symlink or not a directory') if parent_state(path) == :blocked

    exists = File.exist?(target)
    st = File.lstat(path)
    if !st.symlink?
      Item.new(:link, name, path, :conflict, "#{path} exists and is not a symlink")
    elsif File.readlink(path) != target && !(exists && same_file?(path, target))
      Item.new(:link, name, path, :conflict, "points to #{File.readlink(path)}, expected #{target}")
    elsif exists
      Item.new(:link, name, path, :ok, target)
    else
      Item.new(:link, name, path, :missing_target, "target #{target} does not exist")
    end
  rescue Errno::ENOENT
    return Item.new(:link, name, path, :create, target) if File.exist?(target)

    Item.new(:link, name, path, :missing_target, "target #{target} does not exist (skipped)")
  end

  def same_file?(a, b) = File.realpath(a) == File.realpath(b)

  def readme_item(key, description, catalog, path, label)
    content = readme_content(key, description, catalog)
    item = ->(state, detail = nil) { Item.new(:readme, label, path, state, detail).tap { |i| i.instance_variable_set(:@content, content) } }
    st = File.lstat(path)
    return item.(:skipped, 'existing README.md is not generated; left untouched') unless st.file? && owned_readme?(path)

    File.read(path) == content ? item.(:ok) : item.(:update)
  rescue Errno::ENOENT
    item.(:create)
  end

  def owned_readme?(path)
    File.open(path, 'r') { |f| f.gets.to_s.chomp == MARKER }
  end

  def readme_content(key, description, catalog)
    prefix = key == '/' ? '' : "#{key}/"
    dirs = catalog['directories'].select { |n, _| n.start_with?(prefix) && !n.delete_prefix(prefix).include?('/') && n != key }
    links = catalog['links'].select { |l| l['name'].start_with?(prefix) && !l['name'].delete_prefix(prefix).include?('/') }
    lines = [MARKER, '', "# #{key == '/' ? 'Hub' : key}", '', description, '']
    unless dirs.empty? && links.empty?
      lines << '## Contents' << ''
      dirs.sort.each { |n, d| lines << "- `#{File.basename(n)}/` — #{d}" }
      links.sort_by { |l| l['name'] }.each { |l| lines << "- `#{File.basename(l['name'])}` → `#{l['target']}` — #{l['description']}" }
      lines << ''
    end
    lines.join("\n")
  end

  def apply(items, catalog)
    items.each do |item|
      next unless item.pending?

      case item.kind
      when :root then File.chmod(0o700, root)
      when :dir
        raise Error, "#{item.path}: unsafe parent" if parent_state(item.path) == :blocked

        Dir.mkdir(item.path) unless File.directory?(item.path)
      when :link
        raise Error, "#{item.path}: unsafe parent" unless parent_state(item.path) == :ok

        File.symlink(item.detail, item.path)
      when :readme
        raise Error, "#{item.path}: unsafe parent" unless parent_state(item.path) == :ok

        write_atomic(item.path, item.instance_variable_get(:@content), 0o644)
      end
    end
    catalog
  end

  def describe(item)
    label = item.kind == :readme ? "README #{item.name}" : "#{item.kind} #{item.name}"
    item.detail ? "#{label}: #{item.detail}" : label
  end

  def report(items, dry_run:)
    verb = { create: dry_run ? 'would create' : 'created', update: dry_run ? 'would update' : 'updated' }
    items.each do |i|
      case i.state
      when :create, :update then @out.puts "#{verb[i.state]} #{i.kind == :link ? "link #{i.name} -> #{i.detail}" : describe(i)}"
      when :missing_target then @out.puts "missing: #{i.kind} #{i.name}: #{i.detail}"
      when :conflict then @out.puts "conflict: #{i.kind} #{i.name}: #{i.detail} (left untouched)"
      when :skipped then @out.puts "skipped: #{describe(i)}"
      end
    end
    ok = items.count { |i| i.state == :ok }
    bad = items.count(&:problem?)
    @out.puts "#{ok} unchanged#{bad.zero? ? '' : ", #{bad} problem(s)"}"
  end

  def write_atomic(path, content, mode)
    tmp = "#{path}.tmp.#{Process.pid}.#{rand(1 << 32).to_s(16)}"
    File.open(tmp, File::WRONLY | File::CREAT | File::EXCL, mode) do |f|
      f.write(content)
      f.fsync
    end
    File.rename(tmp, path)
  rescue StandardError
    File.unlink(tmp) if tmp && File.exist?(tmp)
    raise
  end

  # --- find -----------------------------------------------------------------

  def walk(dir, logical)
    children = begin
      Dir.children(dir).sort
    rescue SystemCallError
      return
    end
    children.each do |child|
      return if @find[:stopped]
      next if FIND_EXCLUDES.include?(child)

      path = File.join(dir, child)
      child_logical = "#{logical}/#{child}"
      emit_match(File.join(root, child_logical)) if child.downcase.include?(@find[:needle])
      return if @find[:stopped]

      st = File.lstat(path)
      follow = st.directory? || (st.symlink? && @find[:followed].include?(child_logical) && File.directory?(path))
      walk(path, child_logical) if follow
    rescue SystemCallError
      next
    end
  end

  def emit_match(hub_path)
    @out.puts hub_path
    @find[:count] += 1
    @find[:stopped] = true if @find[:count] >= @find[:limit]
  end

  # --- command line ---------------------------------------------------------

  USAGE = <<~TEXT.freeze
    Usage: h hub [--root PATH] COMMAND [ARGS]

    A central hub of symlinks (default root: $H_HUB_ROOT or ~/hub).

    Commands:
      init [CATALOG]              create the hub from CATALOG (default: bundled catalog); re-run = sync
      sync [--dry-run]            create missing directories/symlinks/READMEs; never overwrite
      doctor                      read-only health check; nonzero when unhealthy
      list [QUERY] (ls)           show registered groups and links
      path [NAME]                 print the hub root, or the path of a link/group
      open [NAME]                 open the root, or a link/group, with macOS open
      find NAME QUERY [--limit N] case-insensitive filename search under a link/group (default 100)
      add NAME TARGET DESCRIPTION register a new symlink and sync

    Options: --root PATH, -h/--help
  TEXT

  class CLI
    def self.run(argv, out: $stdout, err: $stderr)
      new(argv, out, err).run
    end

    def initialize(argv, out, err)
      @argv = argv
      @out = out
      @err = err
    end

    def run
      opts, args = parse(@argv)
      cmd = args.shift
      if opts[:help] || cmd.nil? || cmd == 'help'
        @out.puts USAGE
        return 0
      end
      root = opts[:root] || ENV['H_HUB_ROOT'].to_s.then { |r| r.empty? ? '~/hub' : r }
      hub = Hub.new(root: root, out: @out, err: @err)
      dispatch(hub, cmd, args, opts)
    rescue Usage => e
      @err.puts "h-hub: #{e.message}", 'try: h hub --help'
      2
    rescue Error => e
      @err.puts "h-hub: #{e.message}"
      1
    rescue SystemCallError => e
      @err.puts "h-hub: #{e.message}"
      1
    end

    private

    def dispatch(hub, cmd, args, opts)
      allowed = { dry_run: %w[sync], limit: %w[find] }
      allowed.each do |opt, cmds|
        raise Usage, "--#{opt.to_s.tr('_', '-')} only applies to #{cmds.join('/')}" if opts[opt] && !cmds.include?(cmd)
      end
      arity = ->(min, max) { raise Usage, "#{cmd}: expected #{min == max ? min : "#{min}-#{max}"} argument(s)" unless (min..max).cover?(args.size) }
      case cmd
      when 'init'   then arity.(0, 1); hub.init(args[0])
      when 'sync'   then arity.(0, 0); hub.sync(dry_run: opts[:dry_run] || false)
      when 'doctor' then arity.(0, 0); hub.doctor
      when 'list', 'ls' then arity.(0, 1); hub.list(args[0])
      when 'path'   then arity.(0, 1); hub.path(args[0])
      when 'open'   then arity.(0, 1); hub.open(args[0])
      when 'find'   then arity.(2, 2); hub.find(args[0], args[1], limit: opts[:limit] || DEFAULT_LIMIT)
      when 'add'    then arity.(3, 3); hub.add(*args)
      else raise Usage, "unknown command #{cmd.inspect}"
      end
    end

    def parse(argv)
      opts = {}
      args = []
      queue = argv.dup
      until queue.empty?
        tok = queue.shift
        case tok
        when '--' then args.concat(queue.shift(queue.size))
        when '-h', '--help' then opts[:help] = true
        when '--dry-run' then opts[:dry_run] = true
        when '--root' then opts[:root] = queue.shift or raise Usage, '--root needs a PATH'
        when /\A--root=(.+)\z/ then opts[:root] = $1
        when '--limit' then opts[:limit] = limit(queue.shift)
        when /\A--limit=(.*)\z/ then opts[:limit] = limit($1)
        when /\A-./ then raise Usage, "unknown option #{tok}"
        else args << tok
        end
      end
      [opts, args]
    end

    def limit(text)
      n = Integer(text.to_s, 10)
      raise ArgumentError unless (1..MAX_LIMIT).cover?(n)

      n
    rescue ArgumentError
      raise Usage, "--limit must be an integer from 1 to #{MAX_LIMIT}"
    end
  end
end
